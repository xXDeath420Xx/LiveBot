#!/usr/bin/env node
// Regenerates the npm dependency tables in THIRD_PARTY_NOTICES.md from the package-lock.json files.
//
//   node scripts/publish/third-party-notices.mjs [--check]
//
// Everything above the "<!-- generated:start -->" marker is hand-written and kept as is.
// Licences come from each lockfile entry; when an entry has none, node_modules/<pkg>/package.json
// is read (if installed). --check exits 1 when the file is out of date (used in CI).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const FILE = path.join(ROOT, 'THIRD_PARTY_NOTICES.md');
const MARK = '<!-- generated:start -->';
const PROJECTS = [
  ['CertiFried (bot and dashboard)', '.'],
  ['CertiFried Studio (desktop/studio)', 'desktop/studio'],
  ['CertiFried Stream Deck plugin (desktop/streamdeck-plugin)', 'desktop/streamdeck-plugin'],
  ['Dashboard package (dashboard)', 'dashboard'],
  ['Stream relay (stream-relay)', 'stream-relay'],
  ['Cinema (cinema)', 'cinema'],
  ['Windrose agent (windrose-agent)', 'windrose-agent'],
  ['Jellyfin bridge (cf-jellyfin)', 'cf-jellyfin'],
];

function licenceOf(dir, key, entry) {
  if (entry.license) return entry.license;
  try {
    const pj = JSON.parse(fs.readFileSync(path.join(ROOT, dir, key, 'package.json'), 'utf8'));
    if (typeof pj.license === 'string') return pj.license;
    if (pj.license?.type) return pj.license.type;
    if (Array.isArray(pj.licenses)) return pj.licenses.map((l) => l.type || l).join(' OR ');
  } catch { /* not installed */ }
  return 'not stated in package metadata';
}

const esc = (s) => String(s).replace(/\|/g, '\\|');
let out = `${MARK}\n<!-- Generated by scripts/publish/third-party-notices.mjs from the lockfiles. Do not edit below this line. -->\n`;
for (const [title, dir] of PROJECTS) {
  const lockPath = path.join(ROOT, dir, 'package-lock.json');
  if (!fs.existsSync(lockPath)) continue;
  const lock = JSON.parse(fs.readFileSync(lockPath, 'utf8'));
  const rows = [];
  for (const [key, entry] of Object.entries(lock.packages || {})) {
    if (!key || entry.link) continue;
    const name = entry.name || key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length);
    rows.push({ name, version: entry.version || '', licence: licenceOf(dir, key, entry), dev: !!entry.dev, optional: !!entry.optional });
  }
  const seen = new Set();
  const uniq = rows.filter((r) => { const k = `${r.name}@${r.version}`; if (seen.has(k)) return false; seen.add(k); return true; })
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  const tally = {};
  for (const r of uniq) tally[r.licence] = (tally[r.licence] || 0) + 1;
  out += `\n### ${title}\n\n`;
  out += `${uniq.length} packages (${uniq.filter((r) => r.dev).length} development-only). By licence: `;
  out += Object.entries(tally).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${esc(l)} ${n}`).join(', ') + '.\n\n';
  out += '<details><summary>Package list</summary>\n\n| Package | Version | Licence | Use |\n|---|---|---|---|\n';
  for (const r of uniq) out += `| ${esc(r.name)} | ${esc(r.version)} | ${esc(r.licence)} | ${r.dev ? 'dev' : r.optional ? 'optional' : 'runtime'} |\n`;
  out += '\n</details>\n';
}

const current = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8') : '';
const head = current.includes(MARK) ? current.slice(0, current.indexOf(MARK)) : current || '# Third-party notices\n\n';
const next = head + out;
if (process.argv.includes('--check')) {
  if (next !== current) { console.error('THIRD_PARTY_NOTICES.md is out of date: run node scripts/publish/third-party-notices.mjs'); process.exit(1); }
  console.log('THIRD_PARTY_NOTICES.md is up to date');
} else {
  fs.writeFileSync(FILE, next);
  console.log(`wrote ${path.relative(ROOT, FILE)}`);
}
