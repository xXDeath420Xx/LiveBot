#!/usr/bin/env node
/**
 * Generates migrations/089_owo_full_schema.js from upstream's
 * secret/CREATE-OWO-TABLES.sql, adapted for CertiFried:
 *   - Every table prefixed with `owo_`
 *   - User-scoped tables get `guild_id VARCHAR(20)` prepended to PK
 *   - `bigint(20) unsigned` Discord-ID columns normalized to `VARCHAR(20)`
 *   - All FOREIGN KEY constraints stripped (app-level integrity)
 *   - Skipped tables: patreon, surveys, duplicates of systems we already own
 *   - Idempotent via `CREATE TABLE IF NOT EXISTS`
 *
 * Run manually: `node scripts/build-owo-migration.mjs`
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, '..');
const SRC = path.join(REPO, 'docs/Discord-OwO-Bot-master/secret/CREATE-OWO-TABLES.sql');
const OUT = path.join(REPO, 'migrations/089_owo_full_schema.js');

const SKIP = new Set([
    'alter', 'alterbattle', 'alterhunt',
    'blackjack', 'blackjack_card',
    'blacklist', 'feedback', 'rules',
    'boss_ticket', 'boss_weapon', 'boss_weapon_passive', 'guild_boss', 'user_boss',
    'collectibles',
    'disabled',
    'emoji_steal',
    'guild',
    'icecream', 'pizza',
    'marriage', 'propose',
    'patreon_discord', 'patreon_wh', 'patreons',
    'ranking',
    'survey', 'survey_question', 'user_survey',
    'user_ban', 'vote',
]);

const GLOBAL_TABLES = new Set([
    'animals', 'animals_rank', 'backgrounds', 'battle_type', 'buff', 'weapon', 'weapon_passive',
    'gem', 'items', 'announcement', 'quest_types', 'quest_prizes', 'quest_level',
]);

const sql = fs.readFileSync(SRC, 'utf8');

const blockRe = /CREATE TABLE `([a-z_]+)`\s*\(([\s\S]+?)\)\s*ENGINE=InnoDB[^;]*;/gi;
const creates = [];
let m;
while ((m = blockRe.exec(sql)) !== null) {
    creates.push({ name: m[1], body: m[2] });
}

function adapt(name, body) {
    let lines = body.split('\n').map(l => l.replace(/^\s+|\s+$/g, ''));
    lines = lines.filter(l => !/^CONSTRAINT\s+`/i.test(l) && !/^FOREIGN KEY\b/i.test(l));
    lines = lines.map(l => l.replace(/,\s*$/, ','));
    while (lines.length && (lines[lines.length - 1] === '' || lines[lines.length - 1] === ',')) lines.pop();
    if (lines.length) lines[lines.length - 1] = lines[lines.length - 1].replace(/,\s*$/, '');

    lines = lines.map(l => {
        return l.replace(
            /(`(?:id|uid|user_id|guild_id|channel_id|receive|give|target|reference|receiver|giver|gid|tid|owner|from_id|to_id)`)\s+bigint\([0-9]+\)\s+unsigned/gi,
            '$1 VARCHAR(20)'
        );
    });

    const needsGuildId = !GLOBAL_TABLES.has(name);
    if (needsGuildId) {
        const colIdx = lines.findIndex(l => /^`/.test(l));
        if (colIdx >= 0) {
            lines.splice(colIdx, 0, '`guild_id` VARCHAR(20) NOT NULL,');
        }
        lines = lines.map(l => {
            const pk = l.match(/^PRIMARY KEY\s+\((.+)\)(.*)$/i);
            if (pk) return `PRIMARY KEY (\`guild_id\`,${pk[1]})${pk[2]}`;
            return l;
        });
    }

    // AUTO_INCREMENT columns must be first in some key. After we prepend
    // guild_id to PKs, any auto_inc col that was PK-first is now second.
    // Guarantee a UNIQUE KEY on each auto_inc col so MariaDB is happy.
    const autoIncCol = lines
        .map(l => l.match(/^`([a-z_]+)`[^,]*AUTO_INCREMENT/i))
        .find(Boolean)?.[1];
    if (autoIncCol) {
        const hasUnique = lines.some(l =>
            new RegExp(`UNIQUE KEY\\s+\`?\\w+\`?\\s*\\(\`${autoIncCol}\`\\)`, 'i').test(l)
            || new RegExp(`UNIQUE\\s+KEY\\s*\\(\`${autoIncCol}\`\\)`, 'i').test(l)
        );
        const isPkFirst = lines.some(l => new RegExp(`^PRIMARY KEY\\s+\\(\`${autoIncCol}\``, 'i').test(l));
        if (!hasUnique && !isPkFirst) {
            // Append a UNIQUE KEY before closing. Find last key/constraint line.
            const insertAt = lines.length;
            lines[lines.length - 1] = lines[lines.length - 1].replace(/,?\s*$/, ',');
            lines.splice(insertAt, 0, `UNIQUE KEY \`uk_${autoIncCol}\` (\`${autoIncCol}\`)`);
        }
    }

    return `CREATE TABLE IF NOT EXISTS \`owo_${name}\` (\n  ${lines.join('\n  ')}\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;`;
}

const kept = creates.filter(c => !SKIP.has(c.name));
const skipped = creates.filter(c => SKIP.has(c.name));

const stmts = kept.map(c => adapt(c.name, c.body));

const header = `/**
 * Migration 089: Full OwO schema port.
 *
 * Ports upstream OwO Bot's complete table set (CC-BY-NC-SA-4.0) adapted for
 * CertiFried's multi-guild architecture:
 *   - All tables prefixed with \`owo_\`
 *   - User-scoped tables get \`guild_id VARCHAR(20)\` added to PK
 *   - Discord-snowflake columns normalized to VARCHAR(20)
 *   - FK constraints stripped (application-level integrity)
 *
 * Generated by scripts/build-owo-migration.mjs.
 *
 * Ported (${kept.length}): ${kept.map(c => c.name).join(', ')}
 *
 * Skipped (${skipped.length}): ${skipped.map(c => c.name).join(', ')}
 *
 * See LICENSE-OWO-NOTICE.md.
 */

const STATEMENTS = ${JSON.stringify(stmts, null, 2)};

const TABLE_NAMES = ${JSON.stringify(kept.map(c => 'owo_' + c.name), null, 2)};

export async function up(db) {
    for (const stmt of STATEMENTS) {
        await db.execute(stmt);
    }
}

export async function down(db) {
    for (const name of [...TABLE_NAMES].reverse()) {
        await db.execute(\`DROP TABLE IF EXISTS \\\`\${name}\\\`\`);
    }
}
`;

fs.writeFileSync(OUT, header);
console.log(`Wrote ${OUT}`);
console.log(`  Kept: ${kept.length} tables`);
console.log(`  Skipped: ${skipped.length} tables`);
