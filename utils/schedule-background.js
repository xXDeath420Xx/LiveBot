/*
 * Where a schedule card's backdrop comes from.
 *
 * Three sources, one function. The caller does not care which — it asks for a
 * buffer and gets one, or null to mean "draw the gradient instead".
 *
 * Generation is billed per image, and the schedule re-syncs every six hours, so
 * a generated backdrop is kept and reused until the prompt itself changes.
 * Re-billing the same artwork four times a day would be a bug nobody notices
 * until the invoice arrives.
 */
import logger from './logger.js';
import { generateImage, persistImage } from './image-generation.js';
import { discardReplacedUpload } from '../core/server-image-uploads.js';

const TIMEOUT = 120_000;
const MAX_BYTES = 8 * 1024 * 1024;

/** Ask for artwork with nothing in it that pretends to be writing. */
function dressPrompt(prompt, layout) {
    // The model cannot spell, so any lettering it invents is garbage. Asking for
    // none reduces it; the renderer blurs the text zone to deal with the rest.
    const room = layout === 'rows'
        ? 'vertical portrait composition, subject to the edges, calm middle'
        : 'wide cinematic composition, subject on the right, empty space on the left';
    return `${prompt}. ${room}. No text, no words, no letters, no writing, no logos, no watermark.`;
}

/**
 * Describe an image well enough for a generator to imitate it.
 *
 * Deliberately NOT OCR. Tesseract was tried on nine real schedule posters: on the
 * owner's own it found four text boxes and missed the entire day-and-time grid,
 * and on others it read the skull artwork as words. Erasing text it cannot
 * reliably find would delete artwork and leave lettering behind.
 *
 * Palette and tone it can read perfectly, and that is enough to regenerate the
 * same look with no text in it at all — which is the thing a finished poster
 * cannot give us.
 */
export async function describeImage(buffer) {
    const { default: sharp } = await import('sharp');
    const img = sharp(buffer);
    const { data, info } = await img.clone().resize(96, 96, { fit: 'inside' })
        .raw().toBuffer({ resolveWithObject: true });

    const buckets = new Map();
    let lum = 0, sat = 0, n = 0;
    for (let i = 0; i < data.length; i += info.channels) {
        const r = data[i], g = data[i + 1], b = data[i + 2];
        lum += (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
        const max = Math.max(r, g, b), min = Math.min(r, g, b);
        sat += max === 0 ? 0 : (max - min) / max;
        n++;
        // Quantise to 32 levels per channel so near-identical shades group.
        buckets.set(`${r >> 5},${g >> 5},${b >> 5}`, (buckets.get(`${r >> 5},${g >> 5},${b >> 5}`) || 0) + 1);
    }
    const palette = [...buckets.entries()].sort((a2, b2) => b2[1] - a2[1]).slice(0, 5)
        .map(([k]) => '#' + k.split(',').map((v) => (((+v) << 5) + 16).toString(16).padStart(2, '0')).join(''));

    const brightness = lum / n;
    const saturation = sat / n;
    const tone = brightness < 0.25 ? 'very dark, near-black'
        : brightness < 0.45 ? 'dark and moody'
            : brightness < 0.7 ? 'mid-toned' : 'bright and light';
    const punch = saturation > 0.55 ? 'vivid saturated colour'
        : saturation > 0.3 ? 'rich colour' : 'soft muted colour';
    const meta = await img.metadata();
    return {
        palette, brightness, saturation, tone, punch,
        portrait: (meta.height || 1) > (meta.width || 1),
    };
}

/**
 * Turn an uploaded poster into a prompt for a clean version of the same look.
 * `extra` is anything the owner typed to steer it.
 */
export function stylePrompt(style, extra = '') {
    return [
        `${style.tone} poster background`,
        `${style.punch}`,
        `colour palette ${style.palette.join(', ')}`,
        extra && extra.trim(),
        'decorative border, artwork around the edges, calm empty area in the middle for text',
    ].filter(Boolean).join(', ');
}

/**
 * Make a backdrop, and give back a URL for it as well as the bytes.
 *
 * `reference` is the owner's own poster. When the provider can look at it, the
 * words matter far less — it copies the artwork rather than a description of the
 * artwork — so the prompt passed alongside is deliberately about what to REMOVE.
 */
export async function generateBackground(prompt, { layout = 'overlay', reference = null } = {}) {
    const { buffer, contentType, provider } = await generateImage({
        prompt: dressPrompt(prompt, layout),
        reference,
        aspect: layout === 'rows' ? 'portrait' : 'landscape',
        timeout: TIMEOUT,
    });
    if (buffer.length > MAX_BYTES) throw new Error('the generated image is over the 8MB limit');
    const { url } = await persistImage(buffer, { prefix: 'schedule_bg', contentType });
    logger.info(`[ScheduleBg] backdrop generated by ${provider}`, { category: 'twitch' });
    return { url, buffer, provider };
}

/**
 * The instruction for a finished poster.
 *
 * Not a description of it — the provider is looking at the thing. Two things
 * have to go, and the second is the one that is easy to forget: the lettering,
 * AND the layout. Asked only to remove the text, Gemini faithfully redrew the
 * six empty day boxes, which the renderer then drew its own rows on top of —
 * two sets of panels, one showing through the other. What is wanted from an
 * example is its colours and its decoration, never its table.
 */
export function restyleInstruction(extra = '') {
    /* The owner's upload is a FINISHED poster with every day's name, time and
     * description baked into the pixels. Writing fresh schedule text over that
     * produces double text — exactly what shipped on the previous attempt. The
     * only clean path is to generate a BLANK template with the same visual DNA
     * (palette, border decoration, corner character art, background texture)
     * and then overlay text on the empty middle. "Blank" is the whole point:
     * no interior boxes, no day labels, no times, no descriptions, nothing
     * laid out — just the decorative shell. */
    return [
        'Create a completely BLANK stream-schedule background that keeps the',
        'visual DNA of this reference image: the exact colour palette (fire',
        'oranges, ice blues, deep purple-black), the decorative outer border',
        'with its glow and particles, the atmospheric star-field texture, and',
        'any character illustrations that sit in the corners (kitsune, fox,',
        'wolf etc.) at their original positions and scale.',
        'REMOVE EVERYTHING ELSE. No text, no words, no letters, no numbers.',
        'No day names, no times, no titles, no descriptions, no captions, no',
        'watermarks, no logos. No interior panels, no rows, no boxes, no',
        'rectangles, no table or grid structure. No castle vignettes, no scene',
        'illustrations inside the middle of the image. No icons, no emoji.',
        'The middle 75% of the image must be a clean uninterrupted continuation',
        'of the background texture (stars, mist, flames) with NO frames,',
        'placeholder boxes or dividers of any kind.',
        'The result is an EMPTY TEMPLATE: just the ornamental shell around a',
        'clean star-field centre, ready for fresh text to be drawn on top.',
        extra && extra.trim(),
    ].filter(Boolean).join(' ');
}

/** Fetch an image, refusing anything that is not one or is absurdly large. */
export async function download(url) {
    const res = await fetch(url, { signal: AbortSignal.timeout(30_000) });
    if (!res.ok) throw new Error(`image fetch returned HTTP ${res.status}`);
    const type = res.headers.get('content-type') || '';
    if (!type.startsWith('image/')) throw new Error(`that link is ${type || 'not an image'}`);
    const size = Number(res.headers.get('content-length') || 0);
    if (size && size > MAX_BYTES) throw new Error(`image is ${Math.round(size / 1048576)}MB — 8MB is the limit`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length > MAX_BYTES) throw new Error('image is over the 8MB limit');
    return buf;
}

/**
 * Turn one finished poster into a clean backdrop.
 *
 * Two routes to the same place. If the provider can be SHOWN the poster it
 * copies it directly. If it cannot — every Google key spent, and fal-ai is
 * text-only — the palette reading is what is left, and a described backdrop
 * still beats no backdrop. Which one happened is in the log, because the two
 * results do not look equally like the original and it should be possible to
 * tell why.
 */
async function fromExample(source, extra, layout) {
    try {
        const out = await generateBackground(restyleInstruction(extra), {
            layout,
            reference: { buffer: source, contentType: 'image/png' },
        });
        if (out.provider === 'google') return out;
        // fal-ai ignored the reference; redo it properly from the palette.
        logger.info('[ScheduleBg] no image-to-image provider — describing the example instead',
            { category: 'twitch' });
    } catch (e) {
        logger.info(`[ScheduleBg] restyle failed (${e.message}) — describing the example instead`,
            { category: 'twitch' });
    }
    const style = await describeImage(source);
    return generateBackground(stylePrompt(style, extra), { layout });
}

/**
 * Resolve the backdrop for a schedule card.
 *
 * Returns { buffer, mode, cacheUrl } — buffer null means "draw the gradient".
 * Never throws: a backdrop that cannot be fetched must not stop the schedule
 * itself from posting, so it degrades to the drawn one and says so in the log.
 */
/**
 * Choose the next template for a guild.
 *
 * Shuffle deals from a bag rather than rolling each time: every template appears
 * once before any repeats, and the bag never reopens on the image it just closed
 * with. Pure random produces visible repeats — the same card twice running reads
 * as a broken feature even when it is honest chance.
 */
export async function pickTemplate(cfg, pool) {
    const [rows] = await pool.execute(
        'SELECT * FROM schedule_templates WHERE guild_id = ? AND enabled = 1 ORDER BY sort_order, id',
        [cfg.guild_id]);
    if (!rows.length) return null;
    if (rows.length === 1) return rows[0];

    const rotation = cfg.background_rotation || 'fixed';
    if (rotation === 'fixed') return rows[0];
    if (rotation === 'random') return rows[Math.floor(Math.random() * rows.length)];

    // shuffle
    const valid = rows.map((r) => r.id);
    let bag = [];
    try { bag = JSON.parse(cfg.template_bag || '[]').filter((id) => valid.includes(id)); } catch { /* refill */ }
    if (!bag.length) {
        bag = [...valid];
        for (let i = bag.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [bag[i], bag[j]] = [bag[j], bag[i]];
        }
        // Never open a fresh round with the one that closed the last.
        if (bag.length > 1 && bag[0] === cfg.last_template_id) bag.push(bag.shift());
    }
    const chosenId = bag.shift();
    await pool.execute(
        'UPDATE twitch_schedule_sync_config SET template_bag = ?, last_template_id = ? WHERE guild_id = ?',
        [JSON.stringify(bag), chosenId, cfg.guild_id]).catch(() => {});
    return rows.find((r) => r.id === chosenId) || rows[0];
}

export async function resolveBackground(cfg, pool = null) {
    const mode = cfg?.background_mode || 'default';
    try {
        /* Templates, when the guild has uploaded any, replace the single
           background entirely — the rotation is the point of having them. */
        if (pool && mode !== 'default') {
            const tpl = await pickTemplate(cfg, pool);
            if (tpl) {
                if (tpl.cache_url) {
                    try { return { buffer: await download(tpl.cache_url), mode: tpl.mode, template: tpl }; }
                    catch (e) { logger.info(`[ScheduleBg] template ${tpl.id} art expired, regenerating`, { category: 'twitch' }); }
                }
                if (tpl.mode === 'upload') {
                    return { buffer: await download(tpl.source_url), mode: 'upload', template: tpl };
                }
                const source = await download(tpl.source_url);
                const { url, buffer } = await fromExample(source, tpl.prompt || cfg.background_prompt || '',
                    cfg.layout);
                await pool.execute('UPDATE schedule_templates SET cache_url = ? WHERE id = ?', [url, tpl.id])
                    .catch(() => {});
                void discardReplacedUpload(tpl.cache_url, url);   // H-706: the backdrop this one replaces
                return { buffer, mode: 'style', template: tpl, cacheUrl: url };
            }
        }
        if (mode === 'upload' && cfg.background_url) {
            return { buffer: await download(cfg.background_url), mode, cacheUrl: null };
        }
        if (mode === 'style' && cfg.background_url) {
            /* Reuse the art we already paid for. The cache is keyed on the source
               poster, so swapping the reference image regenerates and keeping it
               costs nothing however often the schedule re-syncs. */
            if (cfg.background_cache_url) {
                try {
                    return { buffer: await download(cfg.background_cache_url), mode, cacheUrl: cfg.background_cache_url };
                } catch (e) {
                    logger.info(`[ScheduleBg] cached art expired, regenerating: ${e.message}`, { category: 'twitch' });
                }
            }
            const source = await download(cfg.background_url);
            const { url, buffer } = await fromExample(source, cfg.background_prompt || '', cfg.layout);
            return { buffer, mode, cacheUrl: url };
        }
        if (mode === 'prompt' && cfg.background_prompt) {
            // Reuse what we already paid for, unless the prompt has changed.
            if (cfg.background_cache_url) {
                try {
                    return { buffer: await download(cfg.background_cache_url), mode, cacheUrl: cfg.background_cache_url };
                } catch (e) {
                    logger.info(`[ScheduleBg] cached art expired, regenerating: ${e.message}`, { category: 'twitch' });
                }
            }
            const { url, buffer } = await generateBackground(cfg.background_prompt,
                { layout: cfg.layout });
            return { buffer, mode, cacheUrl: url };
        }
    } catch (e) {
        logger.warn(`[ScheduleBg] ${mode} background unavailable, using the drawn one: ${e.message}`,
            { category: 'twitch' });
    }
    return { buffer: null, mode: 'default', cacheUrl: null };
}

export default {
    resolveBackground, generateBackground, download, describeImage,
    stylePrompt, pickTemplate, restyleInstruction,
};
