import { AttachmentBuilder } from 'discord.js';

/**
 * Attachment builder that will not let you ship an unlabelled image.
 *
 * Discord exposes alt text on message *attachments* through the `description`
 * field (surfaced in the API as `message.attachments[n].description`). It is
 * the only alt-text mechanism available to a bot: images placed inside an embed
 * cannot carry alt text at all, which is a long-standing Discord limitation and
 * the single most-cited gap in its screen-reader support. That makes the
 * attachment path the only accessible one, so anything we render has to use it.
 *
 * Before this helper existed the network had 19 AttachmentBuilder call sites and
 * exactly one of them set a description. Every rank card, welcome banner,
 * schedule graphic and word puzzle reached screen-reader users as an unlabelled
 * blob. Since all of that imagery is generated by us, we know exactly what is in
 * it and have no excuse for not saying so.
 *
 * A missing description throws rather than falling back to something generic.
 * A generic fallback ("an image") is worse than useless — it reads as though the
 * author considered accessibility and decided the content didn't matter — and a
 * silent default would let new call sites regress the thing this module exists
 * to prevent.
 *
 * Since 2026-06-24 Discord also allows editing `description` on an already-sent
 * attachment, so alt text on a long-lived message (a pinned schedule, a live
 * announcement that gets updated in place) can be corrected without a repost.
 */

/** Discord's cap on the attachment description field. */
const MAX_DESCRIPTION_LENGTH = 1024;

/**
 * Collapse whitespace and clamp to Discord's limit.
 * Screen readers announce the description verbatim, so newlines and runs of
 * spaces from template literals become audible pauses if left in.
 */
export function normalizeAltText(text) {
    const collapsed = String(text).replace(/\s+/g, ' ').trim();
    if (collapsed.length <= MAX_DESCRIPTION_LENGTH) return collapsed;
    return `${collapsed.slice(0, MAX_DESCRIPTION_LENGTH - 1)}…`;
}

/**
 * Build an attachment with mandatory alt text.
 *
 * @param {Buffer|string|import('stream').Stream} source Buffer, path or stream.
 * @param {object} options
 * @param {string} options.name     Filename, including extension.
 * @param {string} options.description Alt text describing what the image shows.
 *                                  Describe the *content*, not the medium —
 *                                  "Rank card for Ada: level 12, 3,400 XP,
 *                                  rank 4 of 58" rather than "a rank card image".
 * @returns {AttachmentBuilder}
 */
export function accessibleAttachment(source, { name, description } = {}) {
    if (!name) {
        throw new TypeError('accessibleAttachment: `name` is required.');
    }
    if (!description || !String(description).trim()) {
        throw new TypeError(
            `accessibleAttachment: \`description\` (alt text) is required for "${name}". ` +
            'Describe what the image shows so screen-reader users get the same information ' +
            'sighted users do. See utils/accessible-attachment.js.'
        );
    }

    return new AttachmentBuilder(source, {
        name,
        description: normalizeAltText(description),
    });
}

/**
 * Alt text for a rank/level card.
 * Kept here rather than at the call sites because /level and /rankcard render
 * the same card and should describe it identically.
 */
export function rankCardAltText({ username, level, xp, requiredXp, rank, totalMembers, messages }) {
    const parts = [`Rank card for ${username}.`];
    if (level !== undefined && level !== null) parts.push(`Level ${level}.`);
    if (xp !== undefined && xp !== null) {
        parts.push(requiredXp ? `${formatNumber(xp)} of ${formatNumber(requiredXp)} XP to the next level.` : `${formatNumber(xp)} XP.`);
    }
    if (rank !== undefined && rank !== null) {
        parts.push(totalMembers ? `Ranked ${rank} of ${formatNumber(totalMembers)}.` : `Ranked ${rank}.`);
    }
    if (messages !== undefined && messages !== null) parts.push(`${formatNumber(messages)} messages.`);
    return parts.join(' ');
}

/** Alt text for a welcome/goodbye card. */
export function welcomeCardAltText({ username, guildName, memberCount, kind = 'welcome' }) {
    const verb = kind === 'goodbye' ? 'Farewell' : 'Welcome';
    const parts = [`${verb} card for ${username} in ${guildName}.`];
    if (memberCount !== undefined && memberCount !== null) {
        parts.push(`${formatNumber(memberCount)} members.`);
    }
    return parts.join(' ');
}

function formatNumber(n) {
    const num = Number(n);
    return Number.isFinite(num) ? num.toLocaleString('en-US') : String(n);
}

export { MAX_DESCRIPTION_LENGTH };
